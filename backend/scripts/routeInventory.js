// Static inventory of every Express route and the guards in front of it: authenticate, a role or permission guard, an institute guard, a rate limiter.
//   node scripts/routeInventory.js              summary and the two security lists
//   node scripts/routeInventory.js --markdown   the whole table as Markdown (docs/ROUTE_INVENTORY.md)
//   node scripts/routeInventory.js --json       machine-readable
// It reads the source, it does not start the server. It is a regex scan over each registration line (guards come before the handler on that line), with guard arrays defined in the same file
// (const adminAuth = [authenticate, requireRole(...), ...]) expanded and router.use(authenticate) treated as a blanket guard. test/routeGuards.test.js compares the two security lists with a reviewed
// snapshot, so a new unauthenticated route, or a new signed-in route with no role guard, fails the build until a person has looked at it. Routes declared directly in index.js (health) are not covered.
"use strict";
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "src");
const read = (p) => fs.readFileSync(p, "utf8").split("\r").join("");

// ---- which router file is mounted where (index.js), following one-line re-exports (routes/users.js -> modules/users/users.routes.js)
function mounts() {
  const idx = read(path.join(SRC, "index.js"));
  const requires = {};
  for (const m of idx.matchAll(/const\s+([A-Za-z0-9_]+)\s*=\s*require\("(\.\/[^"]+)"\)/g)) requires[m[1]] = m[2];
  const out = [];
  for (const m of idx.matchAll(/app\.use\("(\/api\/[^"]*)",\s*([A-Za-z0-9_]+)\)/g)) {
    const rel = requires[m[2]];
    if (!rel) continue;
    let file = path.join(SRC, rel) + ".js";
    for (let hops = 0; hops < 3 && fs.existsSync(file); hops++) {
      const re = read(file).match(/module\.exports\s*=\s*require\("([^"]+)"\);?\s*$/m);
      if (!re) break;
      file = path.resolve(path.dirname(file), re[1]) + ".js";
    }
    out.push({ mount: m[1], file });
  }
  return out;
}

function scanFile(file, mount) {
  const src = read(file);
  const defs = {};
  for (const m of src.matchAll(/^const\s+([A-Za-z0-9_]+)\s*=\s*\[([^\]]*)\];?/gm)) defs[m[1]] = m[2];
  const expand = (text) => {
    let out = text;
    for (let i = 0; i < 4; i++) {
      const next = out.replace(/\.\.\.\s*([A-Za-z0-9_]+)|\b([A-Za-z0-9_]+)\b/g, (all, a, b) => (defs[a || b] !== undefined ? defs[a || b] : all));
      if (next === out) break;
      out = next;
    }
    return out;
  };
  const lines = src.split("\n");
  const blanketAt = lines.findIndex((l) => /^\s*router\.use\(/.test(l) && /authenticate/.test(expand(l)));
  const blanket = blanketAt >= 0 ? expand(lines[blanketAt]) : "";
  const routes = [];
  lines.forEach((line, i) => {
    const m = line.match(/^\s*(?:router|r)\.(get|post|put|patch|delete)\(\s*(["'`])([^"'`]*)\2(.*)$/);
    if (!m) return;
    const guards = expand(m[4]) + (blanketAt >= 0 && blanketAt < i ? blanket : "");
    const sub = m[3] === "/" ? "" : m[3];
    routes.push({
      method: m[1].toUpperCase(),
      route: mount + sub,
      file: path.relative(SRC, file).split(path.sep).join("/"),
      auth: /authenticate|requireStudent|requireAuth/.test(guards),
      role: /requireRole|requirePermission|requireAdmin|requireStaff|requireSuperAdmin/.test(guards),
      institute: /attachRequesterInstitute|requireInstitute/.test(guards),
      limiter: /[Ll]imiter/.test(guards),
    });
  });
  return routes;
}

function scanRoutes() {
  const seen = new Set();
  const all = [];
  for (const { mount, file } of mounts()) {
    const key = mount + "|" + file;
    if (seen.has(key) || !fs.existsSync(file)) continue;
    seen.add(key);
    all.push(...scanFile(file, mount));
  }
  return all;
}

const label = (r) => `${r.method} ${r.route}`;
function securityLists(routes = scanRoutes()) {
  return {
    publicRoutes: routes.filter((r) => !r.auth),
    signedInWithoutRoleGuard: routes.filter((r) => r.auth && !r.role),
  };
}

module.exports = { scanRoutes, securityLists, label };

if (require.main === module) {
  const routes = scanRoutes();
  const { publicRoutes, signedInWithoutRoleGuard } = securityLists(routes);
  if (process.argv.includes("--json")) {
    console.log(JSON.stringify(routes, null, 1));
  } else if (process.argv.includes("--markdown")) {
    const byMount = {};
    for (const r of routes) (byMount[r.file] ||= []).push(r);
    console.log(`# Route inventory (generated by \`node scripts/routeInventory.js --markdown\`)\n\n${routes.length} route registrations in ${Object.keys(byMount).length} router files. Static scan: guards are read from the registration line, so treat it as a review aid.\n`);
    console.log("Columns: **auth** = `authenticate` in front; **role** = a role or permission guard; **inst** = an institute guard in the router (the handler may scope as well); **limit** = a rate limiter.\n");
    for (const [file, list] of Object.entries(byMount).sort()) {
      console.log(`## ${file}\n\n| Method | Route | auth | role | inst | limit |\n|---|---|---|---|---|---|`);
      for (const r of list) console.log(`| ${r.method} | \`${r.route}\` | ${r.auth ? "yes" : "**no**"} | ${r.role ? "yes" : "-"} | ${r.institute ? "yes" : "-"} | ${r.limiter ? "yes" : "-"} |`);
      console.log("");
    }
  } else {
    console.log(`${routes.length} route registrations`);
    console.log(`\nPublic (no authenticate): ${publicRoutes.length}`);
    for (const r of publicRoutes) console.log(`  ${label(r).padEnd(60)} ${r.limiter ? "[rate limited]" : "[NO LIMITER]"}`);
    console.log(`\nSigned in but no role/permission guard: ${signedInWithoutRoleGuard.length}`);
    for (const r of signedInWithoutRoleGuard) console.log(`  ${label(r)}`);
  }
}
