// Prints the Module 21 problem bank as a Markdown index (title, topic lesson, difficulty, tags, intended complexity, estimated minutes).
//   node scripts/listPythonBank.js > ../docs/PYTHON_PROBLEM_BANK.md
"use strict";
const { modules } = require("../content/python");

const bank = modules.find((m) => m.module.title.includes("Module 21:"));
if (!bank) throw new Error("Module 21 is not registered");
const rows = [];
for (const chapter of bank.module.chapters) {
  for (const lesson of chapter.lessons) {
    for (const t of lesson.tasks) if (t.meta) rows.push({ lesson: lesson.title.split(":")[0], t });
  }
}
const count = (d) => rows.filter((r) => r.t.meta.difficulty === d).length;
console.log("# Python coding-interview problem bank (Module 21)\n");
console.log(`${rows.length} original practice problems: ${count("EASY")} easy, ${count("MEDIUM")} medium, ${count("HARD")} hard. Generated by \`node backend/scripts/listPythonBank.js\`; the source of truth is \`backend/content/python/m21*.js\`.\n`);
console.log("Every problem has a reference solution that is executed against its sample and hidden cases by `validatePythonContent.js --run`. The *style* tag says what kind of assessment a problem practises (campus online assessment, product-company interview, advanced interview or contest). **No problem is claimed to come from any company.** Time and space complexity are those of the intended solution.\n");
console.log("| # | Problem | Lesson | Level | Topic tags | Time | Space | Minutes |");
console.log("| ---: | --- | --- | --- | --- | --- | --- | ---: |");
rows.forEach(({ lesson, t }, i) => {
  const m = t.meta;
  const topics = m.tags.filter((x) => !x.startsWith("style:")).join(", ");
  console.log(`| ${i + 1} | ${t.title} | ${lesson} | ${m.difficulty.toLowerCase()} | ${topics} | ${m.timeComplexity} | ${m.spaceComplexity} | ${m.minutes} |`);
});
